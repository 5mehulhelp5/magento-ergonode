    public function translate(int $labelIndex, string $languageCode): string
    {
        $parts = explode('_', strtolower(str_replace('-', '_', $languageCode)));
        $language = $parts[0] === 'nb' ? 'no' : $parts[0];
        $script = $language . '_' . ($parts[1] ?? '');
        if ($language === 'cnr') {
            $script = ($parts[1] ?? '') === 'cyrl' ? 'sr' : 'sr_latn';
        }
        $labels = self::LABELS[$script] ?? self::LABELS[$language] ?? self::LABELS['en'];

        return $labels[$labelIndex];
    }
